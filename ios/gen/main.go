const out = "ios/Leaflet/Generated"

func main() {
	log.SetFlags(0)
	if err := os.MkdirAll(filepath.Join(out, "Fonts"), 0o750); err != nil {
		log.Fatal(err)
	}
	write("Strings.swift", stringsSwift())
	write("Palette.swift", paletteSwift())
	for _, f := range []string{"Figtree.ttf", "Figtree-Italic.ttf"} {
		if err := os.Remove(filepath.Join(out, "Fonts", f)); err != nil && !errors.Is(err, fs.ErrNotExist) {
			log.Fatal(err)
		}
	}
	for _, f := range []string{"SourceSerif4.ttf", "SourceSerif4-Italic.ttf"} {
		if err := copyFile(filepath.Join("internal/theme/fonts", f), filepath.Join(out, "Fonts", f)); err != nil {
			log.Fatal(err)
		}
	}
}

func write(name string, b []byte) {
	if err := os.WriteFile(filepath.Join(out, name), b, 0o600); err != nil {
		log.Fatal(err)
	}
}

func copyFile(from, to string) error {
	src, err := os.Open(from) // #nosec G304
	if err != nil {
		return err
	}
	defer func() { _ = src.Close() }()
	dst, err := os.Create(to) // #nosec G304
	if err != nil {
		return err
	}
	if _, err := io.Copy(dst, src); err != nil {
		_ = dst.Close()
		return err
	}
	return dst.Close()
}

