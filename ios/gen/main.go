func swiftName(s string) string {
	if swiftKeywords[s] {
		return "`" + s + "`"
	}
	return s
}

func stringsSwift() []byte {
	meta := sourceMeta()
	keys := make([]string, 0, len(meta))
	for k := range meta {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	var b bytes.Buffer
	b.WriteString(header + "import Foundation\n\n")
	b.WriteString("extension L {\n")
	for _, key := range keys {
		m, _, ok := locales.Catalog.Message("en", key)
		if !ok {
			continue
		}
		info := meta[key]
		for _, line := range strings.Split(strings.TrimSpace(info.Description), "\n") {
			if line != "" {
				fmt.Fprintf(&b, "    /// %s\n", line)
			}
		}
		fmt.Fprintf(&b, "    ///\n    /// \"%s\"\n", strings.ReplaceAll(m.String(), "\n", " "))
		var params, args []string
		seen := map[string]bool{}
		for _, a := range m.Args() {
			if seen[a.Name] {
				continue
			}
			seen[a.Name] = true
			params = append(params, fmt.Sprintf("%s: %s", swiftName(a.Name), swiftType(a, info.Placeholders[a.Name].Type)))
			args = append(args, fmt.Sprintf("%q: %s", a.Name, swiftName(a.Name)))
		}
		if len(params) == 0 {
			fmt.Fprintf(&b, "    static var %s: String { L.text(%q) }\n\n", swiftName(key), key)
			continue
		}
		fmt.Fprintf(&b, "    static func %s(%s) -> String {\n        L.text(%q, [%s])\n    }\n\n",
			swiftName(key), strings.Join(params, ", "), key, strings.Join(args, ", "))
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func swiftType(a i18n.Arg, placeholder string) string {
	switch placeholder {
	case "int":
		return "Int"
	case "double", "num":
		return "Double"
	case "DateTime":
		return "Date"
	case "String":
		return "String"
	}
	switch a.Kind {
	case "plural", "selectordinal":
		return "Int"
	case "number":
		return "Double"
	case "date", "time":
		return "Date"
	}
	return "String"
}

func paletteSwift() []byte {
	var fields []string
	pt := reflect.TypeFor[theme.Palette]()
	colorType := reflect.TypeFor[ui.Color]()
	for i := range pt.NumField() {
		if f := pt.Field(i); f.Type == colorType {
			fields = append(fields, f.Name)
		}
	}
	var b bytes.Buffer
	b.WriteString(header + "import SwiftUI\n\n")
	b.WriteString("/// Palette is the color tokens of internal/theme.\nstruct Palette: Sendable {\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "    var %s: Color\n", lowerFirst(f))
	}
	b.WriteString("    var isDark: Bool\n}\n\n")
	b.WriteString("extension Palette {\n")
	b.WriteString("    /// accents are the accents to choose from, by name, as the settings keep them.\n")
	b.WriteString("    static let accents: [String] = [")
	for i, a := range theme.Accents {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", a.Name)
	}
	b.WriteString("]\n\n")
	b.WriteString("    /// palettes are the palettes by accent, then \"light\", \"dark\" or \"sepia\".\n")
	b.WriteString("    static let palettes: [String: [String: Palette]] = [\n")
	for _, a := range theme.Accents {
		fmt.Fprintf(&b, "        %q: [\n", a.Name)
		for _, mode := range []string{"light", "dark", "sepia"} {
			pal := theme.PaletteFor(mode == "dark", mode == "sepia", a.Name)
			p := &pal
			fmt.Fprintf(&b, "            %q: Palette(\n", mode)
			v := reflect.ValueOf(*p)
			for _, f := range fields {
				c := v.FieldByName(f).Interface().(ui.Color)
				fmt.Fprintf(&b, "                %s: rgb(%d, %d, %d, %s),\n", lowerFirst(f), c.R, c.G, c.B, alpha(c.A))
			}
			fmt.Fprintf(&b, "                isDark: %t),\n", p.Dark)
		}
		b.WriteString("        ],\n")
	}
	b.WriteString("    ]\n\n")
	b.WriteString("    private static func rgb(_ r: Double, _ g: Double, _ b: Double, _ a: Double) -> Color {\n")
	b.WriteString("        Color(.sRGB, red: r / 255, green: g / 255, blue: b / 255, opacity: a)\n    }\n}\n")
	return b.Bytes()
}

func alpha(a uint8) string {
	s := fmt.Sprintf("%.3f", float64(a)/255)
	s = strings.TrimRight(strings.TrimRight(s, "0"), ".")
	if s == "" {
		return "0"
	}
	return s
}

func lowerFirst(s string) string {
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

type messageMeta struct {
	Description  string `json:"description"`
	Placeholders map[string]struct {
		Type string `json:"type"`
	} `json:"placeholders"`
}

func sourceMeta() map[string]messageMeta {
	raw, err := os.ReadFile("locales/en.json")
	if err != nil {
		log.Fatal(err)
	}
	var all map[string]json.RawMessage
	if err := json.Unmarshal(raw, &all); err != nil {
		log.Fatal(err)
	}
	meta := map[string]messageMeta{}
	for k := range all {
		if strings.HasPrefix(k, "@") {
			continue
		}
		var m messageMeta
		if extra, ok := all["@"+k]; ok {
			_ = json.Unmarshal(extra, &m)
		}
		meta[k] = m
	}
	return meta
}
